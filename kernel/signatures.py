def signature_of(key: str, display: str) -> str:
    """取签名；未登记的命令回退为 ``名字[…]``（正常不应发生：已全覆盖，检测会拦）。"""
    sig = SIGNATURES.get(key)
    if sig:
        return sig
    return display + "[…]"


def all_signatures(keys, displays) -> Dict[str, str]:
    return {k: signature_of(k, displays.get(k, k)) for k in keys}
